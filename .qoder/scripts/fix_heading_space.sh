#!/bin/bash
# ============================================================================
# 脚本名称: fix_heading_space.sh
# 功能描述: 修正 Markdown 文件中三级标题和四级标题的格式，在数字编号后添加空格
# 用法: ./fix_heading_space.sh <markdown文件路径> [更多文件...]
# 示例: ./fix_heading_space.sh ./教程.md
#        ./fix_heading_space.sh ./第*.md
# 输入: 匹配格式 "### 1.2.3" 或 "#### 1.2.3"（编号后无空格）
# 输出: 修正为 "### 1.2.3 " 或 "#### 1.2.3 "（编号后添加空格）
# 注意: 已经有空格的标题不会被修改
# 兼容性: POSIX sh（兼容 Linux / macOS）
# ============================================================================

# ---------- 参数检查 ----------
if [ $# -eq 0 ]; then
    echo "用法: $0 <markdown文件路径> [更多文件...]"
    echo "示例: $0 ./教程.md"
    echo "      $0 ./第*.md"
    exit 1
fi

# ---------- 主处理函数 ----------
fix_heading_space() {
    local file="$1"

    # 检查文件是否存在
    if [ ! -f "$file" ]; then
        echo "错误: 文件不存在 - $file"
        return 1
    fi

    # 检查文件是否为 Markdown 文件
    case "$file" in
        *.md|*.markdown) ;;
        *)
            echo "警告: 文件可能不是 Markdown 文件 - $file"
            ;;
    esac

    echo "处理文件: $file"

    # 修正三级标题：在数字编号后添加空格
    # 匹配: ### 1.2.3 或 ### 1.2.3.4（后面没有空格）
    # 替换为: ### 1.2.3 或 ### 1.2.3.4（后面添加空格）
    # 使用 awk 来更精确地匹配
    # 只匹配数字后面直接跟非空格字符的情况
    awk -i inplace '/^###[ \t]+[\.0-9]+[^ \t]/ && !/^###[ \t]+[\.0-9]+[ \t]/ { sub(/^###[ \t]+[\.0-9]+/, "& "); print; next } { print }' "$file"
    
    # 修正四级标题：在数字编号后添加空格
    # 匹配: #### 1.2.3 或 #### 1.2.3.4（后面没有空格）
    # 替换为: #### 1.2.3 或 #### 1.2.3.4（后面添加空格）
    awk -i inplace '/^####[ \t]+[\.0-9]+[^ \t]/ && !/^####[ \t]+[\.0-9]+[ \t]/ { sub(/^####[ \t]+[\.0-9]+/, "& "); print; next } { print }' "$file"

    echo "  ✓ 已修正标题格式"
}

# ---------- 遍历所有参数 ----------
for file in "$@"; do
    fix_heading_space "$file"
done

echo ""
echo "处理完成！"
